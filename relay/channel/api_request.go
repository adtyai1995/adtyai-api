// ErrAmbiguousTaskSubmitTransport marks a sanitized doRequest failure whose raw
// transport error occurred after the request may have been transmitted upstream.
var ErrAmbiguousTaskSubmitTransport = errors.New("upstream error: do request failed")

var proxyCredURLPattern = regexp.MustCompile(`(?i)\b(socks5h?|https?)://([^/\s@]+)@`)

func sanitizeErrorText(text string) string {
	masked := proxyCredURLPattern.ReplaceAllString(text, `$1://***@`)
	return common2.MaskSensitiveInfo(masked)
}

func sanitizeDoRequestError(err error) error {
	if err == nil {
		return nil
	}
	var urlErr *url.Error
	if errors.As(err, &urlErr) && urlErr != nil {
		sanitized := *urlErr
		sanitized.URL = common.SanitizeURLForLog(sanitized.URL)
		if sanitized.Err != nil {
			sanitized.Err = sanitizeDoRequestError(sanitized.Err)
		}
		return &sanitized
	}
	msg := err.Error()
	masked := sanitizeErrorText(msg)
	if masked != msg {
		return errors.New(masked)
	}
	return err
}

func isRawAmbiguousTransportError(err error) bool {
	if err == nil || errors.Is(err, context.Canceled) {
		return false
	}
	var opErr *net.OpError
	if errors.As(err, &opErr) && strings.EqualFold(opErr.Op, "dial") {
		return false
	}
	if errors.Is(err, context.DeadlineExceeded) || errors.Is(err, io.EOF) || errors.Is(err, io.ErrUnexpectedEOF) {
		return true
	}
	var netErr net.Error
	if errors.As(err, &netErr) && netErr.Timeout() {
		return true
	}
	msg := strings.ToLower(err.Error())
	if strings.Contains(msg, "connection refused") || strings.Contains(msg, "no such host") || strings.Contains(msg, "dial tcp") {
		return false
	}
	return strings.Contains(msg, "awaiting headers") ||
		strings.Contains(msg, "connection reset") ||
		strings.Contains(msg, "broken pipe") ||
		strings.Contains(msg, "unexpected eof") ||
		strings.Contains(msg, "timeout")
}

// ApplyUpstreamBodyMetadata restores metadata that net/http cannot infer from
// a ReplayableBody. Callers must pass the original body because NewRequest
// hides its dynamic type behind req.Body's io.ReadCloser wrapper.
func ApplyUpstreamBodyMetadata(req *http.Request, body io.Reader) {
	replayable, ok := body.(common2.ReplayableBody)
	if !ok {
		return
	}

	// BodyStorage structurally satisfies ReplayableBody, but it also exposes
	// io.Closer. If a caller passes the storage directly instead of using
	// NewReplayableBodyReader, hide Close before the transport takes ownership
	// of req.Body so the shared replay source remains available to GetBody.
	if _, rawStorage := body.(common2.BodyStorage); rawStorage {
		req.Body = io.NopCloser(body)
	}

	req.ContentLength = replayable.Size()
	if req.GetBody == nil {
		req.GetBody = replayable.NewReader
	}
}

func SetupApiRequestHeader(info *common.RelayInfo, c *gin.Context, req *http.Header) {
	if info.RelayMode == constant.RelayModeAudioTranscription || info.RelayMode == constant.RelayModeAudioTranslation {
		// multipart/form-data
	} else if info.RelayMode == constant.RelayModeRealtime {
		// websocket
	} else {
		req.Set("Content-Type", c.Request.Header.Get("Content-Type"))
		req.Set("Accept", c.Request.Header.Get("Accept"))
		if info.IsStream && c.Request.Header.Get("Accept") == "" {
			req.Set("Accept", "text/event-stream")
		}
	}
}

const clientHeaderPlaceholderPrefix = "{client_header:"

const (
	headerPassthroughAllKey        = "*"
	headerPassthroughRegexPrefix   = "re:"
	headerPassthroughRegexPrefixV2 = "regex:"
)

var passthroughSkipHeaderNamesLower = map[string]struct{}{
	// RFC 7230 hop-by-hop headers.
	"connection":          {},
	"keep-alive":          {},
	"proxy-authenticate":  {},
	"proxy-authorization": {},
	"te":                  {},
	"trailer":             {},
	"transfer-encoding":   {},
	"upgrade":             {},

	"cookie": {},

	// Additional headers that should not be forwarded by name-matching passthrough rules.
	"host":            {},
	"content-length":  {},
	"content-type":    {},
	"accept-encoding": {},

	// Do not passthrough credentials by wildcard/regex.
	"authorization":  {},
	"x-api-key":      {},
	"x-goog-api-key": {},

	// WebSocket handshake headers are generated by the client/dialer.
	"sec-websocket-key":        {},
	"sec-websocket-version":    {},
	"sec-websocket-extensions": {},
}

const maxHeaderPassthroughRegexLen = 512

var headerPassthroughRegexCache sync.Map // map[string]*regexp.Regexp

func getHeaderPassthroughRegex(pattern string) (*regexp.Regexp, error) {
	pattern = strings.TrimSpace(pattern)
	if pattern == "" {
		return nil, errors.New("empty regex pattern")
	}
	if len(pattern) > maxHeaderPassthroughRegexLen {
		return nil, fmt.Errorf("regex pattern too long (max %d)", maxHeaderPassthroughRegexLen)
	}
	if v, ok := headerPassthroughRegexCache.Load(pattern); ok {
		if re, ok := v.(*regexp.Regexp); ok {
			return re, nil
		}
		headerPassthroughRegexCache.Delete(pattern)
	}
	if _, err := regexp.Compile(pattern); err != nil {
		return nil, err
	}
	compiled, err := regexp.Compile("(?i:" + pattern + ")")
	if err != nil {
		return nil, err
	}
	actual, _ := headerPassthroughRegexCache.LoadOrStore(pattern, compiled)
	if re, ok := actual.(*regexp.Regexp); ok {
		return re, nil
	}
	return compiled, nil
}

func IsHeaderPassthroughRuleKey(key string) bool {
	return isHeaderPassthroughRuleKey(key)
}
func isHeaderPassthroughRuleKey(key string) bool {
	key = strings.TrimSpace(key)
	if key == "" {
		return false
	}
	if key == headerPassthroughAllKey {
		return true
	}
	lower := strings.ToLower(key)
	return strings.HasPrefix(lower, headerPassthroughRegexPrefix) || strings.HasPrefix(lower, headerPassthroughRegexPrefixV2)
}

func shouldSkipPassthroughHeader(name string) bool {
	name = strings.TrimSpace(name)
	if name == "" {
		return true
	}
	lower := strings.ToLower(name)
	if _, ok := passthroughSkipHeaderNamesLower[lower]; ok {
		return true
	}
	return false
}

func applyHeaderOverridePlaceholders(template string, c *gin.Context, apiKey string) (string, bool, error) {
	trimmed := strings.TrimSpace(template)
	if strings.HasPrefix(trimmed, clientHeaderPlaceholderPrefix) {
		afterPrefix := trimmed[len(clientHeaderPlaceholderPrefix):]
		end := strings.Index(afterPrefix, "}")
		if end < 0 || end != len(afterPrefix)-1 {
			return "", false, fmt.Errorf("client_header placeholder must be the full value: %q", template)
		}

		name := strings.TrimSpace(afterPrefix[:end])
		if name == "" {
			return "", false, fmt.Errorf("client_header placeholder name is empty: %q", template)
		}
		if c == nil || c.Request == nil {
			return "", false, fmt.Errorf("missing request context for client_header placeholder")
		}
		clientHeaderValue := c.Request.Header.Get(name)
		if strings.TrimSpace(clientHeaderValue) == "" {
			return "", false, nil
		}
		// Do not interpolate {api_key} inside client-supplied content.
		return clientHeaderValue, true, nil
	}

	if strings.Contains(template, "{api_key}") {
		template = strings.ReplaceAll(template, "{api_key}", apiKey)
	}
	if strings.TrimSpace(template) == "" {
		return "", false, nil
	}
	return template, true, nil
}

// processHeaderOverride applies channel header overrides, with placeholder substitution.
// Supported placeholders:
//   - {api_key}: resolved to the channel API key
//   - {client_header:<name>}: resolved to the incoming request header value
//
// Header passthrough rules (keys only; values are ignored):
//   - "*": passthrough all incoming headers by name (excluding unsafe headers)
//   - "re:<regex>" / "regex:<regex>": passthrough headers whose names match the regex (Go regexp)
//
// Passthrough rules are applied first, then normal overrides are applied, so explicit overrides win.
func processHeaderOverride(info *common.RelayInfo, c *gin.Context) (map[string]string, error) {
	headerOverride := make(map[string]string)
	if info == nil {
		return headerOverride, nil
	}

	headerOverrideSource := common.GetEffectiveHeaderOverride(info)
	// Background polling has no client request from which to copy headers.
	hasClientRequest := !info.IsChannelTest && c != nil && c.Request != nil

	passAll := false
	var passthroughRegex []*regexp.Regexp
	if hasClientRequest {
		for k := range headerOverrideSource {
			trimmedK := strings.TrimSpace(k)
			if trimmedK == "" {
				continue
			}
			if trimmedK == headerPassthroughAllKey {
				passAll = true
				continue
			}
			lowerK := strings.ToLower(trimmedK)

			var pattern string
			switch {
			case strings.HasPrefix(lowerK, headerPassthroughRegexPrefix):
				pattern = strings.TrimSpace(trimmedK[len(headerPassthroughRegexPrefix):])
			case strings.HasPrefix(lowerK, headerPassthroughRegexPrefixV2):
				pattern = strings.TrimSpace(trimmedK[len(headerPassthroughRegexPrefixV2):])
			default:
				continue
			}

			if pattern == "" {
				return nil, types.NewError(fmt.Errorf("header passthrough regex pattern is empty: %q", k), types.ErrorCodeChannelHeaderOverrideInvalid)
			}
			compiled, err := getHeaderPassthroughRegex(pattern)
			if err != nil {
				return nil, types.NewError(err, types.ErrorCodeChannelHeaderOverrideInvalid)
			}
			passthroughRegex = append(passthroughRegex, compiled)
		}
	}

	if passAll || len(passthroughRegex) > 0 {
		for name := range c.Request.Header {
			if shouldSkipPassthroughHeader(name) {
				continue
			}
			if !passAll {
				matched := false
				for _, re := range passthroughRegex {
					if re.MatchString(name) {
						matched = true
						break
					}
				}
				if !matched {
					continue
				}
			}
			value := strings.TrimSpace(c.Request.Header.Get(name))
			if value == "" {
				continue
			}
			headerOverride[strings.ToLower(strings.TrimSpace(name))] = value
		}
	}

	for k, v := range headerOverrideSource {
		if isHeaderPassthroughRuleKey(k) {
			continue
		}
		key := strings.TrimSpace(strings.ToLower(k))
		if key == "" {
			continue
		}

		str, ok := v.(string)
		if !ok {
			return nil, types.NewError(nil, types.ErrorCodeChannelHeaderOverrideInvalid)
		}
		if !hasClientRequest && strings.HasPrefix(strings.TrimSpace(str), clientHeaderPlaceholderPrefix) {
			continue
		}

		value, include, err := applyHeaderOverridePlaceholders(str, c, info.ApiKey)
		if err != nil {
			return nil, types.NewError(err, types.ErrorCodeChannelHeaderOverrideInvalid)
		}
		if !include {
			continue
		}

		headerOverride[key] = value
	}
	return headerOverride, nil
}

func ResolveHeaderOverride(info *common.RelayInfo, c *gin.Context) (map[string]string, error) {
	return processHeaderOverride(info, c)
}

// ApplyHeaderOverride applies channel overrides after the adaptor's headers.
// Without a client request, only static values and {api_key} are resolved.
func ApplyHeaderOverride(info *common.RelayInfo, c *gin.Context, req *http.Request) error {
	headers, err := processHeaderOverride(info, c)
	if err != nil {
		return err
	}
	applyHeaderOverrideToRequest(req, headers)
	return nil
}

func applyHeaderOverrideToRequest(req *http.Request, headerOverride map[string]string) {
	if req == nil {
		return
	}
	for key, value := range headerOverride {
		req.Header.Set(key, value)
		// set Host in req
		if strings.EqualFold(key, "Host") {
			req.Host = value
		}
	}
}

func DoApiRequest(a Adaptor, c *gin.Context, info *common.RelayInfo, requestBody io.Reader) (*http.Response, error) {
	if c == nil || c.Request == nil {
		return nil, errors.New("client request is missing")
	}
	if err := c.Request.Context().Err(); err != nil {
		return nil, types.NewError(err, types.ErrorCodeRequestCancelled, types.ErrOptionWithStatusCode(499), types.ErrOptionWithSkipRetry(), types.ErrOptionWithHideErrMsg("client closed request"))
	}
	fullRequestURL, err := a.GetRequestURL(info)
	if err != nil {
		return nil, fmt.Errorf("get request url failed: %w", err)
	}
	logger.LogDebug(c, "fullRequestURL: %s", common.SanitizeURLForLog(fullRequestURL))
	req, cancel, err := newAPIRequestForMode(c, info, fullRequestURL, requestBody)
	if err != nil {
		var apiErr *types.NewAPIError
		if errors.As(err, &apiErr) {
			return nil, apiErr
		}
		return nil, fmt.Errorf("new request failed: %w", sanitizeDoRequestError(err))
	}
	ApplyUpstreamBodyMetadata(req, requestBody)
	headers := req.Header
	err = a.SetupRequestHeader(c, &headers, info)
	if err != nil {
		if cancel != nil {
			cancel()
		}
		return nil, fmt.Errorf("setup request header failed: %w", err)
	}
	// 在 SetupRequestHeader 之后应用 Header Override，确保用户设置优先级最高
	// 这样可以覆盖默认的 Authorization header 设置
	if err = ApplyHeaderOverride(info, c, req); err != nil {
		if cancel != nil {
			cancel()
		}
		return nil, err
	}
	resp, err := doRequest(c, req, info)
	if err != nil {
		if cancel != nil {
			cancel()
		}
		return nil, fmt.Errorf("do request failed: %w", err)
	}
	if cancel != nil {
		if resp != nil && resp.Body != nil {
			resp.Body = &taskSubmitCancelBody{ReadCloser: resp.Body, cancel: cancel}
		} else {
			cancel()
		}
	}
	return resp, nil
}

// ContentTypeBody is an optional interface implemented by request bodies that
// carry their own Content-Type (for example, regenerated multipart/form-data
// payloads whose boundary differs from the incoming client request).
type ContentTypeBody interface {
	io.Reader
	ContentType() string
}

type formBody struct {
	data        []byte
	reader      *bytes.Reader
	contentType string
}

// NewFormBody wraps generated multipart/form-data bytes together with their
// Content-Type so DoFormRequest can set the upstream header without mutating
// c.Request.Header. It also implements common.ReplayableBody so
// ApplyUpstreamBodyMetadata preserves ContentLength and GetBody.
func NewFormBody(buf *bytes.Buffer, contentType string) ContentTypeBody {
	var data []byte
	if buf != nil {
		data = buf.Bytes()
	}
	return &formBody{
		data:        data,
		reader:      bytes.NewReader(data),
		contentType: contentType,
	}
}

func (b *formBody) Read(p []byte) (int, error) {
	return b.reader.Read(p)
}

func (b *formBody) ContentType() string {
	return b.contentType
}

func (b *formBody) Size() int64 {
	return int64(len(b.data))
}

func (b *formBody) NewReader() (io.ReadCloser, error) {
	return io.NopCloser(bytes.NewReader(b.data)), nil
}

func resolveFormBodyContentType(requestBody io.Reader) string {
	if ctb, ok := requestBody.(interface{ ContentType() string }); ok {
		if ct := strings.TrimSpace(ctb.ContentType()); ct != "" {
			return ct
		}
	}
	return ""
}

// ResolveUpstreamErrorStatus normalizes an HTTP status code for upstream
// error responses that may arrive with HTTP 200. It prefers the first 4xx/5xx
// status found in candidates, then falls back to resp.StatusCode if it is
// 4xx/5xx, and finally defaults to 502 Bad Gateway.
func ResolveUpstreamErrorStatus(resp *http.Response, candidates ...any) int {
	for _, candidate := range candidates {
		switch v := candidate.(type) {
		case int:
			if v >= http.StatusBadRequest && v <= 599 {
				return v
			}
		case int64:
			if v >= http.StatusBadRequest && v <= 599 {
				return int(v)
			}
		case string:
			if n, err := strconv.Atoi(strings.TrimSpace(v)); err == nil && n >= http.StatusBadRequest && n <= 599 {
				return n
			}
		}
	}
	if resp != nil && resp.StatusCode >= http.StatusBadRequest && resp.StatusCode <= 599 {
		return resp.StatusCode
	}
	return http.StatusBadGateway
}

func DoFormRequest(a Adaptor, c *gin.Context, info *common.RelayInfo, requestBody io.Reader) (*http.Response, error) {
	if c == nil || c.Request == nil {
		return nil, errors.New("client request is missing")
	}
	if err := c.Request.Context().Err(); err != nil {
		return nil, types.NewError(err, types.ErrorCodeRequestCancelled, types.ErrOptionWithStatusCode(499), types.ErrOptionWithSkipRetry(), types.ErrOptionWithHideErrMsg("client closed request"))
	}
	fullRequestURL, err := a.GetRequestURL(info)
	if err != nil {
		return nil, fmt.Errorf("get request url failed: %w", err)
	}
	logger.LogDebug(c, "fullRequestURL: %s", common.SanitizeURLForLog(fullRequestURL))
	req, cancel, err := newAPIRequestForMode(c, info, fullRequestURL, requestBody)
	if err != nil {
		var apiErr *types.NewAPIError
		if errors.As(err, &apiErr) {
			return nil, apiErr
		}
		return nil, fmt.Errorf("new request failed: %w", sanitizeDoRequestError(err))
	}
	ApplyUpstreamBodyMetadata(req, requestBody)
	// set form data
	bodyContentType := resolveFormBodyContentType(requestBody)
	if bodyContentType != "" {
		req.Header.Set("Content-Type", bodyContentType)
	} else {
		req.Header.Set("Content-Type", c.Request.Header.Get("Content-Type"))
	}
	headers := req.Header
	err = a.SetupRequestHeader(c, &headers, info)
	if err != nil {
		if cancel != nil {
			cancel()
		}
		return nil, fmt.Errorf("setup request header failed: %w", err)
	}
	// SetupApiRequestHeader copies c.Request.Header.Get("Content-Type") for
	// modes such as ImagesEdits; re-apply the generated multipart body's own
	// Content-Type before ApplyHeaderOverride so the boundary matches the body.
	if bodyContentType != "" {
		req.Header.Set("Content-Type", bodyContentType)
	}
	// 在 SetupRequestHeader 之后应用 Header Override，确保用户设置优先级最高
	// 这样可以覆盖默认的 Authorization header 设置
	if err = ApplyHeaderOverride(info, c, req); err != nil {
		if cancel != nil {
			cancel()
		}
		return nil, err
	}
	resp, err := doRequest(c, req, info)
	if err != nil {
		if cancel != nil {
			cancel()
		}
		return nil, fmt.Errorf("do request failed: %w", err)
	}
	if cancel != nil {
		if resp != nil && resp.Body != nil {
			resp.Body = &taskSubmitCancelBody{ReadCloser: resp.Body, cancel: cancel}
		} else {
			cancel()
		}
	}
	return resp, nil
}

// DoWssRequest dials the adaptor's upstream over WebSocket for the realtime
// and Responses WebSocket relays. It honors the channel proxy, is bound to the
// request context, and reports a rejected handshake as a *types.NewAPIError
// carrying the upstream status code (types.NewError preserves it).
func DoWssRequest(a Adaptor, c *gin.Context, info *common.RelayInfo, requestBody io.Reader) (*websocket.Conn, error) {
	fullRequestURL, err := a.GetRequestURL(info)
	if err != nil {
		return nil, fmt.Errorf("get request url failed: %w", err)
	}
	fullRequestURL = toWebSocketURL(fullRequestURL)
	if targetURL, parseErr := url.Parse(fullRequestURL); parseErr == nil {
		common2.SetContextKey(c, appconstant.ContextKeyUpstreamRequestOrigin, targetURL.Scheme+"://"+targetURL.Host)
	}
	targetHeader := http.Header{}
	err = a.SetupRequestHeader(c, &targetHeader, info)
	if err != nil {
		return nil, fmt.Errorf("setup request header failed: %w", err)
	}
	// 在 SetupRequestHeader 之后应用 Header Override，确保用户设置优先级最高
	// 这样可以覆盖默认的 Authorization header 设置
	headerOverride, err := processHeaderOverride(info, c)
	if err != nil {
		return nil, err
	}
	for key, value := range headerOverride {
		targetHeader.Set(key, value)
	}
	targetHeader.Set("Content-Type", c.Request.Header.Get("Content-Type"))
	dialer := *websocket.DefaultDialer
	transport, transportErr := service.NewRelayTransportWithProxySettings(info.ChannelSetting.Proxy, info.ChannelSetting)
	if transportErr != nil {
		return nil, sanitizeDoRequestError(transportErr)
	}
	dialer.Proxy = transport.Proxy
	if transport.DialContext != nil {
		dialer.NetDialContext = transport.DialContext
	}
	if transport.TLSClientConfig != nil {
		dialer.TLSClientConfig = transport.TLSClientConfig.Clone()
	}
	targetConn, resp, err := dialer.DialContext(c.Request.Context(), fullRequestURL, targetHeader)
	if err != nil {
		if resp != nil && resp.Body != nil {
			_ = resp.Body.Close()
		}
		sanitizedErr := sanitizeDoRequestError(err)
		if helper.ClientRequestCanceled(c) {
			logger.LogWarn(c, common2.LogText("client request canceled during websocket dial to %s: %v", common.SanitizeURLForLog(fullRequestURL), sanitizedErr))
			return nil, types.NewError(sanitizedErr, types.ErrorCodeRequestCancelled, types.ErrOptionWithStatusCode(499), types.ErrOptionWithSkipRetry(), types.ErrOptionWithHideErrMsg("client closed request"))
		}
		statusCode := http.StatusInternalServerError
		if resp != nil {
			statusCode = resp.StatusCode
		}
		return nil, types.NewErrorWithStatusCode(fmt.Errorf("dial failed to %s: %w", common.SanitizeURLForLog(fullRequestURL), sanitizedErr), types.ErrorCodeDoRequestFailed, statusCode)
	}
	return targetConn, nil
}

// toWebSocketURL maps an http(s) endpoint to ws(s). Realtime adaptors already
// return ws(s) URLs, which pass through unchanged.
func toWebSocketURL(raw string) string {
	switch {
	case strings.HasPrefix(raw, "https://"):
		return "wss://" + strings.TrimPrefix(raw, "https://")
	case strings.HasPrefix(raw, "http://"):
		return "ws://" + strings.TrimPrefix(raw, "http://")
	default:
		return raw
	}
}

func DoRequest(c *gin.Context, req *http.Request, info *common.RelayInfo) (*http.Response, error) {
	return doRequest(c, req, info)
}

// keepUpstreamRedirectResponse stops net/http from following redirects while
// returning the upstream 3xx response to the relay without an extra error.
func keepUpstreamRedirectResponse(_ *http.Request, _ []*http.Request) error {
	return http.ErrUseLastResponse
}

func doRequest(c *gin.Context, req *http.Request, info *common.RelayInfo) (*http.Response, error) {
	client, err := service.GetHttpClientWithProxySettings(info.ChannelSetting.Proxy, info.ChannelSetting)
	if err != nil {
		return nil, fmt.Errorf("new proxy http client failed: %w", sanitizeDoRequestError(err))
	}
	// Clients are cached and shared across channels, so override redirect
	// behavior on a shallow copy instead of mutating the cached client. This
	// still reuses its transport and connection pools, including HTTP/2's
	// transparent stream retries.
	relayClient := *client
	relayClient.CheckRedirect = keepUpstreamRedirectResponse
	if common2.DebugEnabled && req != nil && req.URL != nil {
		policy := service.NormalizeHTTPTransportPolicy(info.ChannelSetting)
		logger.LogDebug(c, "http transport select: host=%s protocol=%s shards=%d policy=%s",
			req.URL.Host,
			policy.Protocol,
			policy.Shards,
			policy.String())
	}

	if info.IsStream &&
		!info.DisablePing &&
		info.RelayMode != constant.RelayModeAudioSpeech &&
		info.RelayMode != constant.RelayModeAudioTranscription &&
		info.RelayMode != constant.RelayModeAudioTranslation &&
		info.RelayFormat != types.RelayFormatOpenAIImage &&
		info.RelayMode != constant.RelayModeImagesGenerations &&
		info.RelayMode != constant.RelayModeImagesEdits {
		helper.SetEventStreamHeaders(c)
		// 处理流式请求的 ping 保活
		generalSettings := operation_setting.GetGeneralSetting()
		if generalSettings.PingIntervalEnabled {
			pingInterval := time.Duration(generalSettings.PingIntervalSeconds) * time.Second
			stopPinger := helper.StartStreamKeepAlive(c, pingInterval)
			defer stopPinger()
		}
	}

	common2.SetContextKey(c, appconstant.ContextKeyUpstreamRequestOrigin, req.URL.Scheme+"://"+req.URL.Host)
	resp, err := relayClient.Do(req)
	if err != nil {
		safeErr := sanitizeDoRequestError(err)
		if helper.ClientRequestCanceled(c) && (req == nil || errors.Is(req.Context().Err(), context.Canceled)) {
			logger.LogWarn(c, common2.LogText("client request canceled: %s", safeErr.Error()))
			return nil, types.NewError(safeErr, types.ErrorCodeRequestCancelled, types.ErrOptionWithStatusCode(499), types.ErrOptionWithSkipRetry(), types.ErrOptionWithHideErrMsg("client closed request"))
		}
		logger.LogError(c, common2.LogText("do request failed: %s", safeErr.Error()))
		if isRawAmbiguousTransportError(err) {
			return nil, types.NewError(ErrAmbiguousTaskSubmitTransport, types.ErrorCodeDoRequestFailed)
		}
		return nil, types.NewError(safeErr, types.ErrorCodeDoRequestFailed, types.ErrOptionWithHideErrMsg("upstream error: do request failed"))
	}
	if resp == nil {
		return nil, errors.New("resp is nil")
	}
	if common2.DebugEnabled {
		policy := service.NormalizeHTTPTransportPolicy(info.ChannelSetting)
		logger.LogDebug(c, "http transport negotiated: host=%s protocol=%s shards=%d policy=%s negotiated=%s",
			req.URL.Host,
			policy.Protocol,
			policy.Shards,
			policy.String(),
			resp.Proto)
	}

	if upID := resp.Header.Get(common2.RequestIdKey); upID != "" {
		c.Set(common2.UpstreamRequestIdKey, upID)
	}

	if req != nil && req.Body != nil {
		_ = req.Body.Close()
	}
	if c != nil && c.Request != nil && c.Request.Body != nil {
		_ = c.Request.Body.Close()
	}
	return resp, nil
}

type taskSubmitCancelBody struct {
	io.ReadCloser
	cancel context.CancelFunc
}

func (b *taskSubmitCancelBody) Close() error {
	err := b.ReadCloser.Close()
	if b.cancel != nil {
		b.cancel()
	}
	return err
}

func DoTaskApiRequest(a TaskAdaptor, c *gin.Context, info *common.RelayInfo, requestBody io.Reader) (*http.Response, error) {
	if c == nil || c.Request == nil {
		return nil, errors.New("client request is missing")
	}
	// R5-016: Check cancellation BEFORE transmitting to upstream; once dispatched,
	// detach from client disconnect via context.WithoutCancel with a bounded timeout
	// so an early client disconnect cannot trigger a 100% auto-refund while upstream
	// creates a billable async job.
	if err := c.Request.Context().Err(); err != nil {
		return nil, err
	}
	fullRequestURL, err := a.BuildRequestURL(info)
	if err != nil {
		return nil, err
	}
	submitTimeout := 120 * time.Second
	if common2.RelayTimeout > 0 {
		if configured := time.Duration(common2.RelayTimeout) * time.Second; configured > submitTimeout {
			submitTimeout = configured
		}
	}
	if appconstant.TaskPluginProtocolTimeoutSeconds > 0 {
		if pluginTimeout := time.Duration(appconstant.TaskPluginProtocolTimeoutSeconds) * time.Second; pluginTimeout > submitTimeout {
			submitTimeout = pluginTimeout
		}
	}
	if deadline, ok := c.Request.Context().Deadline(); ok {
		if remaining := time.Until(deadline); remaining > submitTimeout {
			submitTimeout = remaining
		}
	}
	submitCtx, cancel := context.WithTimeout(context.WithoutCancel(c.Request.Context()), submitTimeout)
	req, err := http.NewRequestWithContext(submitCtx, c.Request.Method, fullRequestURL, requestBody)
	if err != nil {
		cancel()
		return nil, fmt.Errorf("new request failed: %w", sanitizeDoRequestError(err))
	}
	ApplyUpstreamBodyMetadata(req, requestBody)
	// Do NOT wrap requestBody in a GetBody closure here: returning the same
	// (already consumed) reader would make any transport-level retry silently
	// replay an empty body. http.NewRequest already derives a correct,
	// snapshot-based GetBody for *bytes.Reader/Buffer/strings.Reader bodies
	// (which most task adaptors pass in); ApplyUpstreamBodyMetadata wires the
	// same contract for bodies that explicitly implement ReplayableBody.
	// Otherwise GetBody stays nil so the transport fails the retry instead of
	// sending a corrupted request.

	err = a.BuildRequestHeader(c, req, info)
	if err != nil {
		cancel()
		return nil, fmt.Errorf("setup request header failed: %w", err)
	}
	if err = ApplyHeaderOverride(info, c, req); err != nil {
		cancel()
		return nil, err
	}
	resp, err := doRequest(c, req, info)
	if err != nil {
		cancel()
		return nil, fmt.Errorf("do request failed: %w", err)
	}
	if resp != nil && resp.Body != nil {
		resp.Body = &taskSubmitCancelBody{ReadCloser: resp.Body, cancel: cancel}
	} else {
		cancel()
	}
	return resp, nil
}

// DetachedNonStreamContext keeps streaming and channel-test requests bound to
// the client disconnect context while detaching billable non-streaming requests
// after dispatch (R-36 #5) so a mid-response client disconnect cannot abort
// upstream response reading and trigger a 100% pre-consume refund.
func DetachedNonStreamContext(c *gin.Context, info *common.RelayInfo, defaultTimeout time.Duration) (context.Context, context.CancelFunc, *types.NewAPIError) {
	var baseCtx context.Context
	if c != nil && c.Request != nil {
		baseCtx = c.Request.Context()
	}
	if baseCtx == nil {
		baseCtx = context.Background()
	}
	if info == nil || info.IsStream || info.IsChannelTest {
		return baseCtx, func() {}, nil
	}
	if err := baseCtx.Err(); err != nil {
		return nil, nil, types.NewError(err, types.ErrorCodeRequestCancelled, types.ErrOptionWithStatusCode(499), types.ErrOptionWithSkipRetry(), types.ErrOptionWithHideErrMsg("client closed request"))
	}
	timeout := defaultTimeout
	if timeout <= 0 {
		timeout = 300 * time.Second
	}
	if common2.RelayTimeout > 0 {
		timeout = time.Duration(common2.RelayTimeout) * time.Second
	}
	if deadline, ok := baseCtx.Deadline(); ok {
		if remaining := time.Until(deadline); remaining > timeout {
			timeout = remaining
		}
	}
	if detacher, ok := info.Billing.(interface{ DetachReservationHeartbeat(time.Duration) }); ok {
		detacher.DetachReservationHeartbeat(timeout + 2*time.Minute)
	}
	upstreamCtx, cancel := context.WithTimeout(context.WithoutCancel(baseCtx), timeout)
	return upstreamCtx, cancel, nil
}

// newAPIRequestForMode keeps streaming and channel-test requests bound to the
// client disconnect context while detaching billable non-streaming requests
// after dispatch (R-36 #5).
func newAPIRequestForMode(c *gin.Context, info *common.RelayInfo, fullRequestURL string, requestBody io.Reader) (*http.Request, context.CancelFunc, error) {
	if c == nil || c.Request == nil {
		return nil, nil, errors.New("client request is missing")
	}
	if info == nil || info.IsStream || info.IsChannelTest {
		req, err := newClientAPIRequest(c, fullRequestURL, requestBody)
		return req, nil, err
	}
	upstreamCtx, cancel, apiErr := DetachedNonStreamContext(c, info, 300*time.Second)
	if apiErr != nil {
		return nil, nil, apiErr
	}
	req, err := http.NewRequestWithContext(upstreamCtx, c.Request.Method, fullRequestURL, requestBody)
	if err != nil {
		cancel()
		return nil, nil, err
	}
	return req, cancel, nil
}

func newClientAPIRequest(c *gin.Context, fullRequestURL string, requestBody io.Reader) (*http.Request, error) {
	if c == nil || c.Request == nil {
		return nil, errors.New("client request is missing")
	}
	ctx := c.Request.Context()
	if ctx == nil {
		ctx = context.Background()
	}
	return http.NewRequestWithContext(ctx, c.Request.Method, fullRequestURL, requestBody)
}
